legacy_supply_curve_test() ->
    ?assert(close(42.7, entso_tables:target_supply_temp(0))),
    ?assert(close(31.8196, entso_tables:target_supply_temp(12))),
    ?assertEqual(60.0, entso_tables:target_supply_temp(-30)),
    ?assertEqual(25.0, entso_tables:target_supply_temp(30)).

assert_points(Fun, Points) ->
    lists:foreach(
        fun({Outdoor, Supply, Expected}) ->
            ?assert(close(Expected, Fun(Outdoor, Supply)))
        end,
        Points
    ).

close(Expected, Actual) ->
    abs(Expected - Actual) < 1.0e-12.
